#!/usr/bin/env python3
"""Export the Python data tables to JSON for the TypeScript MCP server.

Data provenance (no hand-copied, no invented data):
  * data/xid_info.json       <- tools/xid_lookup.py :: XID_INFO
        The Python module states its authoritative source is NVIDIA's
        public XID catalog, https://docs.nvidia.com/deploy/xid-errors/
        (Release 615), cross-checked against Google Cloud's GPU
        troubleshooting guide.
  * data/knowledge_base.json <- rag/knowledge_base.py :: KNOWLEDGE_BASE
        Clean-room runbook chunks written for this project (see that
        module's docstring).

How it works: the source files are parsed with the `ast` module and the
dict literals are extracted with `ast.literal_eval`. The Python modules
are NOT imported/executed, and duplicate dict keys collapse exactly the
way Python itself collapses them at runtime (KNOWLEDGE_BASE defines
`xid-62-pmu` and `xid-92-sbe` twice in source; the runtime dict — and
therefore this export — keeps the last definition, 15 chunks total).

Usage:
    python3 scripts/export_data.py

Re-run this after editing the Python data files, then `npm run build`.
The generated JSON files are committed so the TS server runs without
needing Python at runtime.
"""
from __future__ import annotations

import ast
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parent.parent
OUT_DIR = HERE.parent / "data"


def extract_dict_literal(py_file: Path, var_name: str) -> dict:
    tree = ast.parse(py_file.read_text(encoding="utf-8"), filename=str(py_file))
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == var_name:
                    return ast.literal_eval(node.value)
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            if node.target.id == var_name and node.value is not None:
                return ast.literal_eval(node.value)
    raise SystemExit(f"{var_name} not found in {py_file}")


def main() -> None:
    xid_info = extract_dict_literal(REPO_ROOT / "tools" / "xid_lookup.py", "XID_INFO")
    kb = extract_dict_literal(REPO_ROOT / "rag" / "knowledge_base.py", "KNOWLEDGE_BASE")

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    xid_payload = {
        "source": "tools/xid_lookup.py :: XID_INFO",
        "upstream_authority": "https://docs.nvidia.com/deploy/xid-errors/ (Release 615 catalog)",
        "note": "Generated by scripts/export_data.py — do not edit by hand. "
                "Severity labels are this project's triage heuristics, as in the Python source.",
        # JSON object keys are strings; the TS side parses them back to numbers.
        "entries": {str(code): meta for code, meta in sorted(xid_info.items())},
    }
    (OUT_DIR / "xid_info.json").write_text(
        json.dumps(xid_payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    kb_payload = {
        "source": "rag/knowledge_base.py :: KNOWLEDGE_BASE",
        "note": "Generated by scripts/export_data.py — do not edit by hand. "
                "Duplicate keys in the Python source collapse to the last "
                "definition, matching Python runtime behaviour.",
        "chunks": kb,
    }
    (OUT_DIR / "knowledge_base.json").write_text(
        json.dumps(kb_payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print(f"xid_info.json: {len(xid_info)} codes -> {sorted(xid_info)}")
    print(f"knowledge_base.json: {len(kb)} chunks -> {list(kb)}")


if __name__ == "__main__":
    main()
